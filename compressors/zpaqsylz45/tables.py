def word2(e):
    """SYLZ_TOKENS value -> table word."""
    ll = 31 if e & 0x10000 else e & 0xFF
    ml = 63 if e & 0x20000 else (e >> 8) & 0xFF
    assert (e & 0x10000 == 0 or e & 0xFF == 0) and (e & 0x20000 == 0 or (e >> 8) & 0xFF == 4)
    assert (ll <= 16 or ll == 31) and (ml <= 32 or ml == 63) and e >> 18 == 0
    return ml | ll << 6 | 2 << 11


def word4(e):
    """SYLZ_TOKENS4 value -> table word."""
    prev = 0 if e & 0x20000 else 1
    ll = 31 if e & 0x1000000 else e & 0xFF
    ml = 63 if e & 0x2000000 else (e >> 8) & 0xFF
    assert e & 0x1000000 == 0 or e & 0xFF == 0
    assert e & 0x2000000 == 0 or (e >> 8) & 0xFF == (2 if prev else 4)
    assert (ll <= 16 or ll == 31) and (ml <= 32 or ml == 63) and e & ~0x302FFFF == 0
    return ml | ll << 6 | prev << 11


TABLE = {2: [word2(e) for e in SYLZ_TOKENS], 4: [word4(e) for e in SYLZ_TOKENS4]}
